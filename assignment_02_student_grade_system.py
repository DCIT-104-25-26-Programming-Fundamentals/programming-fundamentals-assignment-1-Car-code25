score = int(input("Enter student score(0-100):  "))

if 80<=score<=100:
     print("Grade: A")

elif 70<=score<=79:
        print("Grade: B")

elif 60<=score<=69:
    print("Grade: C")

elif 50<=score<=59:
    print("Grade: D")

else: 
    print("Grade: F")
